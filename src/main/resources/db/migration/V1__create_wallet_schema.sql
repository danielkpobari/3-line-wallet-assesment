-- Wallet schema. Written to run unchanged on PostgreSQL and on H2 (PostgreSQL mode).

create table users (
    id                  bigint generated by default as identity primary key,
    first_name          varchar(50)              not null,
    last_name           varchar(50)              not null,
    email               varchar(254)             not null,
    -- E.164, e.g. +2347068565534. Required for customers (it doubles as an account number); null for admins.
    phone_number        varchar(14),
    password_hash       varchar(100)             not null,
    role                varchar(20)              not null,
    -- Transaction PIN: customers only (admins have no wallet). Wrong attempts lock it for a while.
    pin_hash            varchar(100),
    failed_pin_attempts integer                  not null default 0,
    pin_locked_until    timestamp with time zone,
    created_at          timestamp with time zone not null,
    constraint uk_users_email unique (email),
    constraint uk_users_phone_number unique (phone_number)
);

create table wallet_balances (
    id         bigint generated by default as identity primary key,
    amount     numeric(19, 2)           not null,
    version    bigint                   not null,
    updated_at timestamp with time zone not null,
    constraint ck_wallet_balances_non_negative check (amount >= 0)
);

create table accounts (
    id                   bigint generated by default as identity primary key,
    account_number       varchar(10)              not null,
    -- The owner's mobile number without the leading 0 (07068565534 -> 7068565534): an alias for account_number.
    phone_account_number varchar(10)              not null,
    user_id              bigint                   not null,
    wallet_balance_id    bigint                   not null,
    currency             varchar(3)               not null,
    status               varchar(20)              not null,
    created_at           timestamp with time zone not null,
    constraint uk_accounts_account_number unique (account_number),
    constraint uk_accounts_phone_account_number unique (phone_account_number),
    constraint uk_accounts_user unique (user_id),
    constraint uk_accounts_wallet_balance unique (wallet_balance_id),
    constraint fk_accounts_user foreign key (user_id) references users (id),
    constraint fk_accounts_wallet_balance foreign key (wallet_balance_id) references wallet_balances (id)
);

create table wallet_transactions (
    id               bigint generated by default as identity primary key,
    reference        varchar(40)              not null,
    idempotency_key  varchar(64),
    transaction_type varchar(20)              not null,
    status           varchar(20)              not null,
    from_account     varchar(10),
    to_account       varchar(10)              not null,
    amount           numeric(19, 2)           not null,
    currency         varchar(3)               not null,
    narration        varchar(100),
    created_at       timestamp with time zone not null,
    constraint uk_wallet_transactions_reference unique (reference),
    constraint uk_wallet_transactions_idempotency_key unique (idempotency_key),
    constraint ck_wallet_transactions_amount_positive check (amount > 0)
);

create index idx_wallet_transactions_created_at on wallet_transactions (created_at);
create index idx_wallet_transactions_from_account on wallet_transactions (from_account);
create index idx_wallet_transactions_to_account on wallet_transactions (to_account);

-- Double-entry ledger: every balance movement is recorded with the balance before and after.
create table ledger_entries (
    id             bigint generated by default as identity primary key,
    transaction_id bigint                   not null,
    account_number varchar(10)              not null,
    entry_type     varchar(10)              not null,
    amount         numeric(19, 2)           not null,
    balance_before numeric(19, 2)           not null,
    balance_after  numeric(19, 2)           not null,
    created_at     timestamp with time zone not null,
    constraint fk_ledger_entries_transaction foreign key (transaction_id) references wallet_transactions (id),
    constraint ck_ledger_entries_amount_positive check (amount > 0)
);

create index idx_ledger_entries_account on ledger_entries (account_number, id);
create index idx_ledger_entries_transaction on ledger_entries (transaction_id);

-- Saved recipients. Each customer can save an account once; the account's holder name is read live via the join.
create table beneficiaries (
    id         bigint generated by default as identity primary key,
    user_id    bigint                   not null,
    account_id bigint                   not null,
    nickname   varchar(50),
    created_at timestamp with time zone not null,
    constraint uk_beneficiaries_user_account unique (user_id, account_id),
    constraint fk_beneficiaries_user foreign key (user_id) references users (id),
    constraint fk_beneficiaries_account foreign key (account_id) references accounts (id)
);

-- Audit trail: who did what, when, from where, and how it ended. Append-only.
-- actor_user_id has no foreign key on purpose: audit records must outlive (and not block) changes to users.
create table audit_events (
    id            bigint generated by default as identity primary key,
    occurred_at   timestamp with time zone not null,
    action        varchar(50)              not null,
    outcome       varchar(10)              not null,
    actor_user_id bigint,
    actor_role    varchar(20),
    resource_type varchar(30),
    resource_id   varchar(64),
    error_code    varchar(50),
    details       varchar(2000),
    request_id    varchar(64),
    ip_address    varchar(45),
    user_agent    varchar(256)
);

create index idx_audit_events_occurred_at on audit_events (occurred_at);
create index idx_audit_events_actor on audit_events (actor_user_id, occurred_at);
create index idx_audit_events_action on audit_events (action, occurred_at);
create index idx_audit_events_resource on audit_events (resource_type, resource_id);
create index idx_audit_events_request on audit_events (request_id);
